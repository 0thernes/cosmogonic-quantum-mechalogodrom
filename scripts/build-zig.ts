#!/usr/bin/env bun
/**
 * Compiles `zig/src/root.zig` (Zig 0.17.0) to `zig/zig-out/cqm_kernels.wasm`
 * (`wasm32-freestanding`, ReleaseSmall) and emits `src/math/zig-wasm-binary.ts`
 * so the WASM kernel module runs synchronously in Bun, Node, and browser
 * environments with zero filesystem or network I/O.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const OUT_DIR = join(ROOT, 'zig', 'zig-out');
const WASM_PATH = join(OUT_DIR, 'cqm_kernels.wasm');
const TS_OUT = join(ROOT, 'src', 'math', 'zig-wasm-binary.ts');

mkdirSync(OUT_DIR, { recursive: true });

const exports = [
  'cqm_gray_scott_step',
  'cqm_tdse_step',
  'cqm_qgt_fubini_study',
  'cqm_rosette_fnv1a64',
  'cqm_pq_wire_bytes',
  'cqm_georefine_verify_frame',
];

const verProc = Bun.spawnSync(['zig', 'version'], { cwd: ROOT });
const zigVersion = verProc.exitCode === 0 ? verProc.stdout.toString().trim() : '0.17.0';

const buildArgs = [
  'zig',
  'build-exe',
  'zig/src/root.zig',
  '-fno-entry',
  '-O',
  'ReleaseSmall',
  '-target',
  'wasm32-freestanding',
  ...exports.map((e) => `--export=${e}`),
  `-femit-bin=${WASM_PATH}`,
];

const proc = Bun.spawnSync(buildArgs, { cwd: ROOT, stderr: 'pipe', stdout: 'pipe' });
if (proc.exitCode !== 0) {
  console.error('zig build-exe failed:', proc.stderr.toString());
  process.exit(proc.exitCode ?? 1);
}

const wasmBytes = readFileSync(WASM_PATH);
const b64 = wasmBytes.toString('base64');
const sha256 = createHash('sha256').update(wasmBytes).digest('hex');

const tsSource = `/**
 * Auto-generated by \`scripts/build-zig.ts\` from \`zig/src/root.zig\`.
 * Compiler: Zig ${zigVersion} (\`wasm32-freestanding\`, \`ReleaseSmall\`).
 * Byte length: ${wasmBytes.length} B | SHA-256: ${sha256}
 */

export const CQM_ZIG_COMPILER_VERSION = '${zigVersion}' as const;
export const CQM_ZIG_WASM_BYTE_LENGTH = ${wasmBytes.length} as const;
export const CQM_ZIG_WASM_SHA256 = '${sha256}' as const;
export const CQM_ZIG_WASM_BASE64 =
  '${b64}' as const;

export function decodeZigWasmBytes(): Uint8Array<ArrayBuffer> {
  if (typeof Buffer !== 'undefined') {
    return new Uint8Array(Buffer.from(CQM_ZIG_WASM_BASE64, 'base64'));
  }
  const bin = atob(CQM_ZIG_WASM_BASE64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) {
    out[i] = bin.charCodeAt(i);
  }
  return out;
}
`;

writeFileSync(TS_OUT, tsSource, 'utf8');
console.log(
  `[build:zig] Zig ${zigVersion} -> ${WASM_PATH} (${wasmBytes.length} B, sha256=${sha256.slice(0, 16)}...)`,
);
